// Computes each character's drawn (x, y, line) position and advance width
// for a given wrap width, without drawing anything -- shared by the actual
// render (drawGlyphs) and by mouse hit-testing / cursor placement, so
// wrapping logic only exists in one place.
//
// Wrapping is character-based, not word-based: once a line has stamped
// WRAP_WIDTH px worth of advances, the next character starts the next
// line at TEXT_X instead -- and if that next character is a space, it's
// dropped (skip: true, zero advance) rather than becoming a leading space
// on the new line. A literal "\n" forces the same line break regardless
// of width. There's room for exactly two lines, so anything past the
// second line's own wrap point (or a second "\n") is marked skip and
// parked at the current position rather than starting a third line.
function layoutText(str, maxWidth, tallText = false) {
  const positions = [];
  let x = TEXT_X;
  let line = 0;
  for (let i = 0; i < str.length; i++) {
    const ch = str[i];
    if (ch === "\n") {
      positions.push({ x, y: TEXT_Y + line * LINE_HEIGHT, line, advance: 0, skip: true });
      if (line === 0 && !tallText) {
        line = 1;
        x = TEXT_X;
      }
      continue;
    }
    if (x - TEXT_X >= maxWidth) {
      if (line !== 0 || tallText) {
        positions.push({ x, y: TEXT_Y + line * LINE_HEIGHT, line, advance: 0, skip: true });
        continue;
      }
      line = 1;
      x = TEXT_X;
      if (ch === " ") {
        positions.push({ x, y: TEXT_Y + line * LINE_HEIGHT, line, advance: 0, skip: true });
        continue;
      }
    }
    const g = BITMAP_FONT.glyphs[ch];
    const adv = g ? g.adv : BITMAP_FONT.glyphs[" "].adv;
    positions.push({ x, y: TEXT_Y + line * LINE_HEIGHT, line, advance: adv, skip: !g });
    x += adv + LETTER_SPACING;
  }
  positions.push({ x, y: TEXT_Y + line * LINE_HEIGHT, line, advance: 0, skip: true });
  return positions;
}

// Stamps text as literal 1x1 pixel squares from BITMAP_FONT, extracted
// directly from assets/glyphs.png. Each glyph row is a string of digits:
// '0' transparent (the sheet's white background), '1' the glyph's own dark
// ink, '2' the glyph's own lighter tone -- both colors come from the actual
// reference image, not a computed shadow/outline.
function drawGlyphs(targetCtx, str, positions, tallText = false) {
  for (let i = 0; i < str.length; i++) {
    const p = positions[i];
    if (p.skip) continue;
    const g = BITMAP_FONT.glyphs[str[i]];
    if (!g) continue;
    const { text: textColor, outline: outlineColor } = colorAt(i);
    const gx = Math.round(p.x);
    for (let row = 0; row < g.rows.length; row++) {
      const bits = g.rows[row];
      for (let col = 0; col < bits.length; col++) {
        const bit = bits[col];
        if (bit === "0") continue;
        targetCtx.fillStyle = bit === "1" ? textColor : outlineColor;
        const scale = tallText ? 2 : 1;
        targetCtx.fillRect(gx + col, p.y + row * scale, 1, scale);
      }
    }
  }
}

// Converts a mouse/pointer event's page coordinates into canvas-pixel
// space, accounting for the CSS zoom applied by applyZoom().
function canvasPointFromEvent(e) {
  const rect = canvas.getBoundingClientRect();
  const scaleX = canvas.width / rect.width;
  const scaleY = canvas.height / rect.height;
  return { x: (e.clientX - rect.left) * scaleX, y: (e.clientY - rect.top) * scaleY };
}

// Finds the character index nearest a canvas-space point, for click-to-
// place-cursor and drag-to-select. Picks the line by y, then walks that
// line's positions left to right, landing on whichever side of each
// glyph's midpoint the point falls on.
function hitTest(mx, my) {
  const line = my < TEXT_Y + LINE_HEIGHT ? 0 : 1;
  let best = -1;
  for (let i = 0; i < lastPositions.length; i++) {
    const p = lastPositions[i];
    if (p.line !== line) continue;
    if (best === -1) best = i;
    if (mx >= p.x + p.advance / 2) best = i;
  }
  return best === -1 ? lastPositions.length - 1 : best;
}

async function renderArrow(targetCtx, box) {
  if (!arrowToggle.checked) return;

  const arrowColors = ARROW_COLORS[box.file];
  if (!arrowColors) return;

  const arrowImg = await loadImage(ARROW_IMAGE);
  if (!arrowImg) return;

  // Create temporary canvas for color replacement
  const tempCanvas = document.createElement("canvas");
  tempCanvas.width = arrowImg.width;
  tempCanvas.height = arrowImg.height;
  const tempCtx = tempCanvas.getContext("2d");
  tempCtx.drawImage(arrowImg, 0, 0);

  // Replace colors: left (#283028) and right (#717979)
  const imageData = tempCtx.getImageData(0, 0, tempCanvas.width, tempCanvas.height);
  const data = imageData.data;

  const leftRGB = hexToRgb(arrowColors.left);
  const rightRGB = hexToRgb(arrowColors.right);
  const oldLeftRGB = { r: 0x28, g: 0x30, b: 0x28 };
  const oldRightRGB = { r: 0x71, g: 0x79, b: 0x79 };

  const tolerance = 10;
  for (let i = 0; i < data.length; i += 4) {
    const r = data[i];
    const g = data[i + 1];
    const b = data[i + 2];

    const isLeft = Math.abs(r - oldLeftRGB.r) <= tolerance && Math.abs(g - oldLeftRGB.g) <= tolerance && Math.abs(b - oldLeftRGB.b) <= tolerance;
    const isRight = Math.abs(r - oldRightRGB.r) <= tolerance && Math.abs(g - oldRightRGB.g) <= tolerance && Math.abs(b - oldRightRGB.b) <= tolerance;

    if (isLeft) {
      data[i] = leftRGB.r;
      data[i + 1] = leftRGB.g;
      data[i + 2] = leftRGB.b;
    } else if (isRight) {
      data[i] = rightRGB.r;
      data[i + 1] = rightRGB.g;
      data[i + 2] = rightRGB.b;
    }
  }

  tempCtx.putImageData(imageData, 0, 0);
  targetCtx.drawImage(tempCanvas, 241, 28);
}

function hexToRgb(hex) {
  const result = /^#?([a-f\d]{2})([a-f\d]{2})([a-f\d]{2})$/i.exec(hex);
  return result ? {
    r: parseInt(result[1], 16),
    g: parseInt(result[2], 16),
    b: parseInt(result[3], 16)
  } : { r: 0, g: 0, b: 0 };
}

async function render() {
  const box = BOXES[selectedIndex];
  const img = await loadImage(BOX_IMAGE_DATA[box.file]);
  if (!img) return;

  canvas.width = CANVAS_W;
  canvas.height = CANVAS_H;

  ctx.imageSmoothingEnabled = false;
  ctx.clearRect(0, 0, CANVAS_W, CANVAS_H);

  const offsetX = Math.round((CANVAS_W - box.w) / 2);
  const offsetY = Math.round((CANVAS_H - box.h) / 2);
  ctx.drawImage(img, offsetX, offsetY);

  // Adjust TEXT_X based on box type and system message setting
  if (box.file === "type17.png" || box.file === "type13.png" || box.file === "type16.png") {
    TEXT_X = systemMessageToggle.checked ? 21 : 17;
  } else {
    TEXT_X = systemMessageToggle.checked ? 20 : 16;
  }

  const tallText = tallTextToggle.checked;
  TEXT_Y = tallText ? 6 : 8;
  if (box.file === "type15.png") TEXT_Y += 1;

  const text = smartQuotes(rawText);
  const positions = layoutText(text, WRAP_WIDTH, tallText);
  lastText = text;
  lastPositions = positions;

  if (selStart !== selEnd) {
    const s = Math.min(selStart, selEnd);
    const e = Math.max(selStart, selEnd);
    ctx.fillStyle = "rgba(91, 141, 239, 0.45)";
    const highlightHeight = tallText ? LINE_HEIGHT * 2 : LINE_HEIGHT;
    for (let i = s; i < e; i++) {
      const p = positions[i];
      const w = p.advance || 3;
      ctx.fillRect(p.x, p.y, w, highlightHeight);
    }
  }

  drawGlyphs(ctx, text, positions, tallText);

  if (document.activeElement === canvas) {
    const p = positions[selEnd] ?? positions[positions.length - 1];
    ctx.fillStyle = "#000000";
    const cursorHeight = tallText ? LINE_HEIGHT * 2 : LINE_HEIGHT;
    ctx.fillRect(Math.round(p.x), p.y, 1, cursorHeight);
  }

  await renderArrow(ctx, box);

  applyZoom();
}

// Scales the preview up as large as will fit inside the preview frame
// (integer multiples only, so pixels stay crisp) with no manual zoom control
// and no cropping -- the whole frame is always visible.
function applyZoom() {
  const availW = previewFrame.clientWidth - 32; // minus frame padding
  const availH = previewFrame.clientHeight - 32;
  const maxZoomW = Math.floor(availW / canvas.width);
  const maxZoomH = Math.floor(availH / canvas.height);
  const zoom = Math.max(1, Math.min(maxZoomW, maxZoomH, 8));
  canvas.style.width = `${canvas.width * zoom}px`;
  canvas.style.height = `${canvas.height * zoom}px`;
}

