// Shifts/clips existing color ranges to follow an edit from oldText to
// newText, using the standard common-prefix/common-suffix diff: whatever
// changed is treated as one replaced span, boundaries before it are left
// alone, boundaries after it shift by the length delta, boundaries that
// fell entirely inside the replaced span are dropped (that text is gone,
// don't stretch the old segment to cover whatever replaced it), and
// boundaries that straddle the edit are clipped to whichever side survives.
function shiftSegments(oldText, newText) {
  const oldLen = oldText.length;
  const newLen = newText.length;
  let prefix = 0;
  const maxPrefix = Math.min(oldLen, newLen);
  while (prefix < maxPrefix && oldText[prefix] === newText[prefix]) prefix++;
  let suffix = 0;
  const maxSuffix = Math.min(oldLen, newLen) - prefix;
  while (suffix < maxSuffix && oldText[oldLen - 1 - suffix] === newText[newLen - 1 - suffix]) suffix++;
  const oldEditEnd = oldLen - suffix;
  const newEditEnd = newLen - suffix;
  const delta = newEditEnd - oldEditEnd;

  const shifted = [];
  for (const seg of segments) {
    const { start, end } = seg;
    if (end <= prefix) {
      shifted.push({ ...seg });
    } else if (start >= oldEditEnd) {
      shifted.push({ ...seg, start: start + delta, end: end + delta });
    } else if (start >= prefix && end <= oldEditEnd) {
      // entirely inside the replaced span -- that text is gone, drop it
    } else {
      const newStart = start < prefix ? start : newEditEnd;
      const newEnd = end > oldEditEnd ? end + delta : prefix;
      if (newStart < newEnd) shifted.push({ ...seg, start: newStart, end: newEnd });
    }
  }
  return mergeAdjacent(shifted);
}

function mergeAdjacent(segs) {
  const sorted = [...segs].sort((a, b) => a.start - b.start);
  const merged = [];
  for (const seg of sorted) {
    const prev = merged[merged.length - 1];
    if (prev && prev.end === seg.start && prev.text === seg.text && prev.outline === seg.outline) {
      prev.end = seg.end;
    } else {
      merged.push({ ...seg });
    }
  }
  return merged;
}

// Applies a color to [start, end) of the raw text, splitting/clipping any
// existing ranges that overlap it.
function applyColorToRange(start, end, text, outline) {
  if (start >= end) return;
  const next = [];
  for (const seg of segments) {
    if (seg.end <= start || seg.start >= end) {
      next.push(seg);
      continue;
    }
    if (seg.start < start) next.push({ ...seg, end: start });
    if (seg.end > end) next.push({ ...seg, start: end });
  }
  next.push({ start, end, text, outline });
  segments = mergeAdjacent(next);
}

